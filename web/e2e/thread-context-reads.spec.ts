import { expect, test } from "@playwright/test"

test("each read Context shows its name and only the states worth noticing", async ({ page }) => {
  await page.goto("/e2e/thread-context-reads.html")
  const reads = page.locator("#reads")
  await expect(reads).toContainText("已读上下文 4")
  await expect(reads).toContainText("#10–#32")
  const manual = reads.getByRole("link", { name: /必读上下文/ })
  await expect(manual).toHaveText("必读上下文")
  await expect(manual).toHaveAttribute("href", "#/contexts?context=8f1d2e3a-4b5c-6d7e-8f90-1a2b3c4d5e6f")
  await expect(manual).toHaveAttribute("title", "8f1d2e3a-4b5c-6d7e-8f90-1a2b3c4d5e6f\n最近读取 #27\n读取 2 次")
  await expect(reads.getByRole("link", { name: /LOL-MODEL/ })).toHaveText("LOL-MODEL已改")
  await expect(reads.getByRole("link", { name: /LOL-MODEL/ })).toHaveAttribute("title", /读取之后这个上下文被改过/)
  await expect(reads.getByRole("link", { name: /未知上下文/ }).first()).toHaveText("未知上下文未读到")
  await expect(reads.getByRole("link", { name: /未知上下文/ }).nth(1)).toHaveText("未知上下文已不存在")
  // The chip carries no id or fingerprint: a UUID means nothing to a reader.
  await expect(reads).not.toContainText("8f1d2e3a")
  await expect(reads).not.toContainText("aaaaaaaa")
  // The read count is detail, not a chip label.
  await expect(reads).not.toContainText("×2")
  const empty = page.locator("#empty")
  await expect(empty).toContainText("已读上下文 0")
  await expect(empty).toContainText("本窗口内没有读取上下文")
  await expect(empty.getByRole("link")).toHaveCount(0)
})

test("the header shows the Contexts the controller already asked the model to re-read", async ({ page }) => {
  await page.goto("/e2e/thread-context-reads.html")
  const notice = page.locator("#notice")
  await expect(notice).toContainText("上下文已变更，已要求模型重读")
  await expect(notice).toContainText("控制器在本次请求里插入了这条 developer 消息")
  await expect(notice.getByRole("link", { name: "LOL-MODEL" })).toHaveAttribute("href", "#/contexts?context=c0ffee00-1111-2222-3333-444455556666")
  await expect(notice.getByRole("link", { name: "必读上下文" })).toHaveAttribute("title", "8f1d2e3a-4b5c-6d7e-8f90-1a2b3c4d5e6f")
  await expect(notice).toContainText("#42")
})

test("the indicator speaks both languages and keeps its layout in either theme", async ({ page }) => {
  await page.goto("/e2e/thread-context-reads.html")
  await page.getByRole("button", { name: "Theme", exact: true }).click()
  await page.getByRole("button", { name: "Language", exact: true }).click()
  const reads = page.locator("#reads")
  await expect(reads).toContainText("Read contexts 4")
  await expect(reads).toContainText("#10–#32")
  await expect(reads.getByRole("link", { name: /必读上下文/ })).toHaveAttribute("title", /read 2 times/)
  await expect(reads.getByRole("link", { name: /LOL-MODEL/ })).toHaveText("LOL-MODELedited")
  await expect(reads.getByRole("link", { name: /Unknown context/ }).first()).toHaveText("Unknown contextnot read")
  await expect(reads.getByRole("link", { name: /Unknown context/ }).nth(1)).toHaveText("Unknown contextgone")
  await expect(page.locator("#empty")).toContainText("no context read in this window")
  await expect(page.locator("#notice")).toContainText("Contexts changed — the model was asked to re-read")
})
