import { expect, test } from "@playwright/test"

test("every read Context shows its id, the fingerprint it read, and whether the Context moved on", async ({ page }) => {
  await page.goto("/e2e/thread-context-reads.html")
  const reads = page.locator("#reads")
  await expect(reads).toContainText("已读上下文 4")
  await expect(reads).toContainText("#10–#32")
  const manual = reads.getByRole("link", { name: /必读上下文/ })
  await expect(manual).toContainText("#8f1d2e3a")
  await expect(manual).toContainText("aaaaaaaa")
  await expect(manual).toContainText("×2")
  await expect(manual).not.toContainText("已改")
  await expect(manual).toHaveAttribute("href", "#/contexts?context=8f1d2e3a-4b5c-6d7e-8f90-1a2b3c4d5e6f")
  await expect(manual).toHaveAttribute("title", "8f1d2e3a-4b5c-6d7e-8f90-1a2b3c4d5e6f\n最近读取 #27\n读取 2 次\n读取时内容 aaaaaaaaaaaaaaaa\n现在内容 aaaaaaaaaaaaaaaa")
  const edited = reads.getByRole("link", { name: /LOL-MODEL/ })
  await expect(edited).toContainText("bbbbbbbb")
  await expect(edited).toContainText("已改")
  await expect(edited).toHaveAttribute("title", /读取时内容 bbbbbbbbbbbbbbbb\n现在内容 cccccccccccccccc/)
  const unanswered = reads.getByRole("link", { name: /未知上下文/ }).first()
  await expect(unanswered).toContainText("#11112222")
  await expect(unanswered).toContainText("未读到")
  await expect(unanswered).not.toContainText("dddddddd")
  const gone = reads.getByRole("link", { name: /未知上下文/ }).nth(1)
  await expect(gone).toContainText("eeeeeeee")
  await expect(gone).toContainText("已不存在")
  const empty = page.locator("#empty")
  await expect(empty).toContainText("已读上下文 0")
  await expect(empty).toContainText("本窗口内没有读取上下文")
  await expect(empty.getByRole("link")).toHaveCount(0)
})

test("the indicator speaks both languages and keeps its layout in either theme", async ({ page }) => {
  await page.goto("/e2e/thread-context-reads.html")
  await page.getByRole("button", { name: "Theme", exact: true }).click()
  await page.getByRole("button", { name: "Language", exact: true }).click()
  const reads = page.locator("#reads")
  await expect(reads).toContainText("Read contexts 4")
  await expect(reads).toContainText("#10–#32")
  await expect(reads.getByRole("link", { name: /必读上下文/ })).toHaveAttribute("title", /read 2 times/)
  await expect(reads.getByRole("link", { name: /LOL-MODEL/ })).toContainText("edited")
  await expect(reads.getByRole("link", { name: /Unknown context/ }).first()).toContainText("not read")
  await expect(reads.getByRole("link", { name: /Unknown context/ }).nth(1)).toContainText("gone")
  await expect(page.locator("#empty")).toContainText("no context read in this window")
})
